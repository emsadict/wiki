  <h2 style="color: #1781cc; border-bottom: 2px solid #1781cc; padding-bottom: 5px;">
    Wiki Loves Women
  </h2>
  <p>
    One of our core advocacy programs that focuses on bridging the gender gap on the internet is the <strong>Wiki Loves Women</strong> project. 
    It aims to release and widely share cultural and educational content related to women. The project collaborates with organizations and institutions 
    to draw their existing information onto Wikipedia, making it available to millions worldwide.
  </p>
  <p>
    The Wiki Loves Women project is organized in collaboration with <strong>Wiki In Africa</strong> and supported by the <strong>Wikimedia Foundation</strong>. 
    From 2016–2017, it was also run in partnership with the <strong>Goethe-Institut</strong> and operated across four West African countries: Côte d'Ivoire, Ghana, Cameroon, and Nigeria.
    See the project documentation here: 
    <a href="https://en.wikipedia.org/wiki/Wikipedia:WikiProject_Wiki_Loves_Women/Nigeria" target="_blank" style="color: #1781cc;">https://en.wikipedia.org/wiki/Wikipedia:WikiProject_Wiki_Loves_Women/Nigeria</a>
  </p>

  <h2 style="color: #1781cc; margin-top: 40px; border-bottom: 2px solid #1781cc; padding-bottom: 5px;">
    Visibility Project
  </h2>
  <p>
    The <strong>Visibility Project for East Africa</strong> is a gender-focused initiative in partnership with 
    <strong>African Women in Media</strong> and <strong>UNESCO</strong>. It trained more than 200 female journalists from East Africa in the 
    basics of Wikipedia editing and copyright principles.
  </p>
  <p>
    Launched on 5 June 2020 and concluded on 6 July 2020, it was jointly facilitated by 
    <strong>Wikimedia User Group Nigeria</strong>, <strong>Wikimedia Community User Group Tanzania</strong>, and 
    <strong>Wikimedia Community User Group Uganda</strong>. African Women in Media and UNESCO provided logistical support.
  </p>

