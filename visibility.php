    Visibility Project – East Africa
  </h2>

  <p>
    The <strong>Visibility Project for East Africa</strong> is a gender-focused initiative launched in partnership with 
    <strong>African Women in Media</strong> and the <strong>United Nations Educational, Scientific and Cultural Organization (UNESCO)</strong>. 
    The program aimed to train female journalists in East Africa on the fundamentals of Wikipedia editing and copyright literacy.
  </p>

  <p>
    As part of our mission to bridge the gender gap online and recruit women contributors to Wikipedia, more than 
    <strong>200 East African journalists</strong> were trained between <strong>5th June – 6th July 2020</strong>. 
    The training sessions were conducted online and coordinated by <strong>Wikimedia User Group Nigeria</strong>, 
    <strong>Wikimedia Community User Group Tanzania</strong>, and <strong>Wikimedia Community User Group Uganda</strong>, 
    with logistical support from our partners at African Women in Media and UNESCO.
  </p>

