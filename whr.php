The Wikimedia User Group Nigeria has been involved in several advocacy programs to promote Wikipedia and other Wikimedia projects in Nigeria and to bridge the gender gap on the internet. These advocacy programs have not only improved the use of Wikipedia in Nigeria but has led to an increase in the number of contributors to Wikipedia and other sister's project.
Wikipedia – Emmanuella goes to school
Wikipedia – Things come together

New Readers Awareness Campaign In 2017, Wikimedia User Group Nigeria collaborated with the Wikimedia Foundation to launch a major Wikipedia awareness campaign in Nigeria. To support the awareness work in Nigeria, we collaborated with an organization called Anakle. Anakle specializes in video production, digital design, and marketing, with an office in Lagos. They provided creative development for this project, offered experienced perspectives on how to appeal to our target audience and how to produce appealing video content. They collaborated with us on channel approaches, developing a strategic overview of digital media platforms where we can share videos to reach people who are unfamiliar with Wikipedia. Anakle led all video production in the project. We selected scripts based on "Okonkwo" character from Chinua Achebe's Things Fall Apart, and "Emmanuella" – a prominent Nigerian web comedian. Two videos were released in October 2017, receiving over 10 million combined views. This advocacy work earned the team the 2018 African Excellence Awards, and the award ceremony took place in Dublin, Ireland. </p>
            
                <p style="text-align: justify;">The WikiForHumanRights on Human Trafficking in Nigeria was organised from the 5th March 2022 to 15th of April 2022. A 2-days event was organised in partnership with the National Agency for the Prohibition of Trafficking in Persons, Action Against Trafficking in Persons and Smuggling of Migrants (A-TIPSOM) Nigeria, Nigeria Police Force, Yoruba Wikimedians User Group, Igbo Wikimedians User Group, Hausa Wikimedians User Group, and the Nigeria Immigration Service. It was held at IBIS Hotel, Ikeja, Lagos State from 29th of March to 30th of March 2022. There were representatives from of the partners. More than 50 people participated in the event, and more than 40 communities participated in the event. More than 100 articles were contributed to the English, Yoruba, and Hausa language Wikipedia and the event was broadcasted nationally by the Nigerian Television Authority. It was the first time the Wikimedia User Group Nigeria will be collaborating with law enforcement agencies to bridge contents gap on the internet (and specifically on Wikipedia). Participants were selected from all the six geopolitical states of Nigeria. The project was supported by the European Union. Alex Stinson, Senior Program Strategist, Wikimedia Foundation attended as a special guests, and joined the participants online. </p>
                
