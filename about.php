                                                    <p style="text-align: justify;">Wikimedia User Group Nigeria/Wikimedia Radio and TV Program On the 11th of January 2017, the Wikimedia User Group Nigeria launched an awareness program to promote Wikipedia and other sister projects and to create awareness for Wikimedia activities in Nigeria. We began with a weekly radio program at the Tech Radio. The radio program was birthed by a Wiki Loves Women event in Nigeria. It features live interviews of content partners from Wiki Loves Women and also Wikimedians across the globe. It was live on air between 19:45 to 20:45 h (West Africa Time) every Wednesday.

                                                       <p style="text-align: justify;">Wiki Women Radio Program To strengthen our advocacy work, the Wikimedia Nigeria User Group Nigeria partnered with WFM 91.7 FM on 23rd August 2017. The objectives of the partnership included but not limited to creating awareness about Wikimedia projects, increasing content, increasing reach, encouraging donations of women-related content, and increasing the number of women contributors to Wikimedia projects. WFM 91.7 MHz is a Nigerian specialized radio station licensed by Nigerian Broadcasting Commission (NBC) to broadcast programs that focus primarily on women and their families. It is the first female-oriented radio station in Sub-Saharan Africa. It is headquartered at the Arepo community, Ogun State, South West, Nigeria. This program features notable women in all spheres of life. Notable women who have featured on the program include Chinedum Peace Babalola, a Nigerian Professor of Pharmacy and the Vice-Chancellor of Chrisland University and Lola Akinmade Åkerström, an award-winning Nigerian photographer and travel writer based in Stockholm, Sweden. She is the editor-in-chief for Slow Travel Stockholm.</p>
                                                       <p style="text-align: justify;">Group Photograph: Wiki Loves Women

Wiki Loves Women One of our core advocacy programs that focuses on bridging the gender gap on the internet is the Wiki Loves Women project. It is a project that aims to release and make widely available cultural and educational content on, or related to women, to the general public. The project works with organizations and public institutions to draw their existing information onto Wikipedia, and via this platform be made available to millions of people every day. The Wiki Loves Women project is organized in collaboration with Wiki In Africa and supported by Wikimedia Foundation. In 2016–2017 the project was run in collaboration with the Goethe Institute and was active on the ground in four West African countries: Côte d’Ivoire, Ghana, Cameroon, and Nigeria. See the project documentation here.</p>
                                                       </p>
                                                       <p style="text-align: justify;">Visibility project The Visibility Project for East Africa is a gender-focus initiative in partnership with the African Women in Media, and the United Nations Educational, Scientific and Cultural Organization (UNESCO) to train female journalists in East Africa on the basics of Wikipedia editing and copyrights. It’s one of our initiatives to bridge the gender gap on the internet and to recruit female contributors to Wikipedia. More than 200 Journalists from East-Africa were trained on how to contribute to Wikipedia. The project started on the 5th of June 2020 and ended on 6th July 2020. Series of online training was organized and facilitated by the Wikimedia User Group Nigeria, Wikimedia Community User Group Tanzania and the Wikimedia Community User Group Uganda. The logistics support was provided by the African Women in Media, and the United Nations Educational, Scientific, and Cultural Organization (UNESCO).</p>
