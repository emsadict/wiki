            <h5>History</h5>
            <p style="text-align: justify;">The Wikimedia User Group Nigeria was recognized by the Affiliations Committee of the Wikimedia Foundation on the 28th September 2015. 
                Our first activity as a recognized affiliate was the Wiki Loves Africa 2015 tagged Africa’s Culture in fashion and Adornment.
                 This was followed by the Workshop for Students of Fountain University, a two-day workshop organized for students of Fountain University, as part of Wikipedia 15. 
                 Having operated as a Wikimedia User Group Nigeria for more than 6 years, the user group registered with the Corporate Affairs Commission, 
                 Nigeria as a charitable organization and nonprofit organization in Nigeria on the 31st of October 2018. We are proposing to be recognized as a Wikimedia Chapter in Nigeria.
                  Our proposed name is Wikimedia Nigeria. The Wikimedia User Group Nigeria shall act as the official chapter of the Wikimedia Foundation in Nigeria.
                   Our primary objective is to promote free access to knowledge through Wikipedia and other sisters projects run by the Wikimedia Foundation. 
                   We are committed to the development, growth and free distribution of educational contents in Nigeria.
                    We empower people to contribute to Wikipedia and other sister projects to ensure that knowledge is freely accessible . We share the ideal of a world in which every single 
                human being can freely share in the sum of all knowledge, and here in Nigeria we shall play a key role in actualization of that vision
            </p>
            <h5>Leadership</h5>
            <p style="text-align: justify;">
All corporate powers shall be exercised by or under the authority of, and the business and affairs of the Wikimedia User Group Nigeria shall be managed under the direction of the Board of Trustees either directly or through a written delegation of authority. The authorized number of Trustees of Wikimedia Nigeria shall be at least seven (7). Trustees shall be selected according to the process specified in Article IV, Section 3 of the organization’s Bylaws. Each Trustee shall hold office until the expiration of his or her term as specified in Article IV, Section 3 of the Bylaws, or until his or her earlier resignation, removal from office, or death.

The board of trustees of the Wikimedia User Group Nigeria is currently composed of three (3) Community-selected Trustees and seven (7) board-appointed Trustees

