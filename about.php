                                                    <p style="text-align: justify;">The Wikimedia User Group Nigeria strongly believed that Wikipedia and its sister’s projects belong in education. We realized that students constitute the highest users of Wikipedia and resources and this makes it imperative to develop a strategy that targets students’ participation in our projects, programs, and activities that promote free knowledge.</p>
                                                    <p style="text-align: justify;">Wikimedia Fan Club in Nigeria The Wikimedia User Group Nigeria designed this program as an outreach program with the aim of taking Wikimedia projects to all the tertiary institutions in Nigeria. The program was originally conceptualized to support the result of the New Readers Outreach Survey conducted in Nigeria in the year 2016 which revealed that only 23% of internet users in Nigeria are aware of Wikipedia. Out of the 23% population that have shown awareness of Wikipedia are the Nigerian students with 43%.</p>
                                                    <p style="text-align: justify;">Each club is a registered association in all the designated institutions and they are coordinated by an experienced member of the club appointed by the proposed Wikimedia User Group Nigeria leadership.
                                                    </p>
                                                    <p style="text-align: justify;">Today, we have a Wikimedia Fan Club in at least seven tertiary institutions in Nigeria namely: The Univerity of Ibadan Fan Club, Wikimedia Fan Club, University of Ilorin, Wikimedia Hub, Nigerian Institute of Journalism (NIJ), Wikimedia Fan Club, Ekiti State University, Wiki Club, Lagos State University (LASU), Wikimedia Fan Club, Federal University of Agriculture, Abeokuta,Wikimedia Hub Enugu domiciled at the University of Nigeria and Wikimedia Fan Club Kwara State University.</p>
                                                    <p style="text-align: justify;">The User Group has organized a series of training for students of tertiary institutions in Nigeria, which began in 2016 when the students of Fountain University were trained. Several pieces of training and edit-a-thon have been organized across multiple tertiary institutions including, at the University of Lagos, The University of Ibadan, Ekiti State University, the University of Ilorin, University of Nigeria, Nigerian Institute of Journalism (NIJ), Federal University of Agriculture, Abeokuta, University of Nigeria, University of Benin, Kwara State University, Lagos State Polytechnic, to mention a few. </p>
                                                    
                                                    <p style="text-align: justify;">The Wikimedia User Group Nigeria has a strong relationship with the management of some of the major tertiary institutions in Nigeria. On the 22nd of October 2018, the Wikimedia User Group Nigeria presented an award to Professor Olanrewaju Fagbohun, the Vice-Chancellor of the University of Lagos for his contribution to open knowledge and education in Nigeria</p>
