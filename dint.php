            <Center><h3>Decolonise the Internet</h3></Center>
            <hr />
            <p style="text-align: justify;">The Decolonise the Internet is a gender-focus initiative in partnership with the Goethe Institut to promote the participation of women in bridging the content gap about women on the internet and to increase the quality of women-related contents on Wikipedia. "During its inception, the internet was seen as a vital instrument for democracy and equality. In 2020, amidst a global pandemic and racial inequalities that are very much still alive, it is time to ask: Whose stories are told and who is telling these stories on the internet? And how do Artificial Intelligence, Algorithms and Bots shape our view of the world and perpetuate racisms? This is where the new Goethe-Institut project “Decolonise The Internet” sees its core.</p>
            <p style="text-align: justify;">The Goethe-Institut’s “Decolonise the Internet” focuses on bridging the unequal representation of voices from the Global South on the internet and aims to increase awareness on how AI and algorithms might perpetuate racisms".[1]</p>
            <p style="text-align: justify;">The project facilitated by the Goethe Institut, Wikimedia Nigeria Foundation Inc. in collaboration with the Yoruba Wikimedians User Group, Igbo Wikimedians User Group & Hausa Wikimedians User Group started on the 5th of September 2020. More than 100 females were trained on how to contribute to Wikipedia. The logistics supports were provided by the Goethe Institut. This was followed by a contest that resulted in the creation of over 1,500+ articles in English, Hausa, Igbo and Yoruba language</p>
