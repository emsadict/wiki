  <h2 style="color: #1781cc; border-bottom: 2px solid #1781cc; padding-bottom: 5px;">Training Sessions</h2>
  <p>
    Participants were trained by experienced Wikipedia editors from Nigeria. At least five (5) training sessions were conducted between 
    <strong>28th September 2020</strong> and <strong>27th October 2020</strong>, covering the following topics:
  </p>
  <ul style="color: #333;">
    <li><strong>Copyrights & Free License(s):</strong> Facilitated by <em>User:Samatics</em> & <em>Isaac Olatunde</em>, an experienced license reviewer at Wikimedia Commons</li>
    <li><strong>Cheat Sheet of Wikipedia Editing:</strong> Facilitated by <em>User:Jamie Tubers</em>, a seasoned English Wikipedia editor</li>
    <li><strong>Basic Wikipedia Editing & How to Cite a Wikipedia Article:</strong> Facilitated by <em>User:Uzoma Ozurumba</em> from the Igbo Wikimedia Community</li>
    <li><strong>Work-Flow of Creating a Wikipedia Page:</strong> Facilitated by <em>Ayokanmi Oyeyemi</em>, regional ambassador of the 1Lib1Ref project</li>
    <li><strong>Translation to Local Language Wikipedia:</strong> Facilitated by <em>User:Macdanpets</em> & <em>User:Olaniyan Olushola</em></li>
  </ul>
  <p><em>Moderated by Yinka Maja and managed by Olaniyan Olushola.</em></p>

  <h3 style="color: #1781cc; margin-top: 40px;">Learning</h3>

  <h4 style="margin-top: 20px;">What Worked Well</h4>
  <ol>
    <li><strong>Diversity of participants and trainers:</strong> Over 300 people applied; 70% of selected participants were women from diverse language communities. This fostered networking and made the sessions dynamic.</li>
    <li><strong>Diversity of trainers:</strong> Selected from Nigeria's English, Yoruba, Hausa & Igbo communities. Trainers were experienced, multilingual, and culturally relevant.</li>
    <li><strong>WhatsApp group coordination:</strong> Provided a cost-effective, accessible, and real-time support platform for trainers and participants.</li>
  </ol>

  <h4 style="margin-top: 30px;">What Did Not Work So Well</h4>
  <ol>
    <li><strong>Internet connection:</strong> Connectivity was a challenge, though using two different network providers mitigated it slightly.</li>
    <li><strong>Communication:</strong> Despite a strong history of collaboration with Goethe-Institut, miscommunication affected certain aspects—particularly around contest judging criteria and the social media campaign. Thanks to Katja’s adaptability, resolution was achieved.</li>
  </ol>

  <h4 style="margin-top: 30px;">What We Plan to Improve</h4>
  <p>
    Future projects will prioritize <strong>clear communication</strong>. We’ll ensure timely publication of key information on the project page and stronger internal coordination among partners.
  </p>

