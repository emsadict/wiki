  <h2 style="color: #1781cc; border-bottom: 2px solid #1781cc;">Wikimedia User Group Nigeria Fan Clubs</h2>

  <p>
    The <strong>Wikimedia Fan Club in Nigeria</strong> is an outreach program developed by Wikimedia User Group Nigeria to introduce Wikimedia projects into 
    tertiary institutions. Originating from the 2016 <em>New Readers Outreach Survey</em>, which showed that only 23% of Nigerian internet users are aware 
    of Wikipedia (with 43% among students), the initiative aims to close that awareness gap through on-campus engagement.
  </p>

  <p>
    Each Fan Club is a recognized association within its institution and is coordinated by experienced members appointed by WUGN leadership.
    Fan Clubs exist in at least seven Nigerian institutions including:
  </p>
  <ul>
    <li>University of Ibadan</li>
    <li>University of Ilorin</li>
    <li>Nigerian Institute of Journalism (NIJ)</li>
    <li>Ekiti State University</li>
    <li>Lagos State University (LASU)</li>
    <li>Federal University of Agriculture, Abeokuta</li>
    <li>University of Nigeria, Enugu Campus (Wikimedia Hub Enugu)</li>
    <li>Kwara State University</li>
  </ul>

  <p>
    WUGN has organized training programs since 2016, starting with students of Fountain University. Activities have spanned numerous institutions including 
    the University of Lagos, University of Benin, and Lagos State Polytechnic. On October 22, 2018, WUGN presented an award to 
    <strong>Professor Olanrewaju Fagbohun</strong> (VC, University of Lagos) for contributions to open knowledge.
  </p>

  <h3 style="color: #1781cc;">Reactivation of the NIJ Fan Club</h3>
  <p>
    In July 2022, the Nigerian Institute of Journalism Fan Club was revitalized through an in-person event led by 
    <strong>Kayode Yusuf</strong>. The election of new leaders saw <strong>Ms. Kemi Makinde</strong> appointed as club president. 
    Activities included an orientation, social discussions, and community planning sessions.
  </p>

  <h3 style="color: #1781cc;">Kwara State University (KWASU) Fan Club: Wiki Loves Monuments</h3>
  <p>
    With microgrant support, the KWASU Fan Club organized a <strong>Wiki Loves Monuments</strong> photo walk on September 16, 2022, 
    visiting landmarks like <em>Sobi Hill</em>, <em>Crushed Rock Sango</em>, and <em>Dada Pottery, Ilorin</em>. 
    <strong>268 images</strong> were uploaded to Wikimedia Commons. 
    More on the metrics is available on the <a href="https://outreachdashboard.wmflabs.org/" target="_blank">project dashboard</a>.
  </p>

  <h3 style="color: #1781cc;">WikiVibrance Campaign at KWASU</h3>
  <p>
    In partnership with the <strong>WikiVibrance Project</strong>, the club trained youth on editing and tracking contributions. 
    Two online trainings were hosted, followed by participation in a youth-focused radio segment on <strong>KWASU 103.9 FM</strong>. 
    <strong>29 participants</strong> tracked their work via the 
    <a href="https://outreachdashboard.wmflabs.org/" target="_blank">Wikimedia Outreach Dashboard</a>.
  </p>

  <h3 style="color: #1781cc;">University of Ibadan & Ilorin: WikiVibrance 2022</h3>
  <p>
    On October 14, 2022, the University of Ibadan Fan Club celebrated <strong>International Youth Day</strong> as part of WikiVibrance with 20 participants. 
    Meanwhile, the University of Ilorin hosted an edit-a-thon for <strong>Africa Youth Month</strong> supported by WikiVibrance and the 
    <strong>Africa Knowledge Initiative</strong>. Over <strong>40 new articles</strong> were created and <strong>82 existing articles</strong> improved. 
    Top 10 contributors were rewarded with data packages.
  </p>

  <h3 style="color: #1781cc;">Lagos State University (LASU): Fan Club Recognition & Activities</h3>
  <p>
    On November 30, 2022, LASU’s Student Affairs unit received and approved all required documentation for official recognition of the fan club. 
    The approval was finalized on December 5, 2022. Soon after, on December 10, a training and edit-a-thon titled <strong>"Wiki-Ethnicity and Tribes"</strong> 
    was held with <strong>40 student participants</strong>, including a contest and numerous new editors.
  </p>

  <h3 style="color: #1781cc;">KWASU Leads Wiki-in-School Program</h3>
  <p>
    In April 2023, the <strong>KWASU Fan Club</strong> launched the <strong>Wiki-In-School Program</strong>. 25 students were selected and trained, with 
    article assignments evaluated via the <a href="https://outreachdashboard.wmflabs.org/" target="_blank">Outreach Dashboard</a>. 
    Their work was highlighted in the Wikimedia <a href="https://meta.wikimedia.org/wiki/Education/News" target="_blank">Education Newsletter</a>.
  </p>
