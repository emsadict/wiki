  <div style="max-width: 950px; margin: 40px auto; font-family: Arial, sans-serif; line-height: 1.6;">

  <h2 style="color: #1781cc; border-bottom: 2px solid #1781cc;">Conference Participation and Hosting</h2>

  <p>
    Members of <strong>Wikimedia User Group Nigeria</strong> (WUGN) have actively participated in several international and local conferences organized by the Wikimedia Foundation and its global community. 
    These events are instrumental in knowledge exchange, collaboration, and deepening engagement with Wikimedia projects across the continent.
  </p>

  <h3 style="color: #1781cc;">WikiMaster Conference – Lagos, January 2018</h3>
  <p>
    In collaboration with <strong>World of Knowledge (WOK)</strong>, WUGN hosted a 3-day conference at the <strong>Goethe-Institut, Lagos</strong>, aimed at building a strong WOK community in Nigeria using Wikipedia as a tool. 
    The event was widely covered by local media, including <em>BBC Pidgin, TVC, and STV</em>, and raised awareness about both <strong>Wikimaster</strong> and Wikimedia projects. 
    It remains one of the group’s largest outreach events.
  </p>

  <h3 style="color: #1781cc;">Wiki Indaba Conference – Abuja, 2019</h3>
  <p>
    From <strong>November 8–10, 2019</strong>, WUGN hosted <strong>Wiki Indaba 2019</strong> in Abuja, Nigeria, with support from the <strong>Wikimedia Foundation</strong> and <strong>Google LLC</strong>. 
    Despite a reduced headcount compared to 2018, the conference boasted greater diversity — participants from <strong>23 countries</strong> and over <strong>40% female representation</strong>. 
    WMF staff, including the Chief Operating Officer and 10 team members, were present. Feedback from across the African Wikimedia movement was resoundingly positive.
  </p>

  <h3 style="color: #1781cc;">Wikimedia Conference & GLAM – Tel Aviv 2018</h3>
  <p>
    WUGN Chair <strong>Olaniyan Olushola</strong> participated in both conferences in 2018. 
    <strong>Sam Oye</strong> also represented the group at the Wikimedia Conference that same year. 
    Members of the user group have consistently joined events like <strong>Wikimania</strong>, <strong>Wiki Indaba</strong>, and the <strong>Wiki Education Conference</strong> to share insights and strengthen collaboration.
  </p>

  <h3 style="color: #1781cc;">Wiki Indaba 2021 – Rwanda</h3>
  <p>
    Four community members received scholarships to attend Wiki Indaba in Rwanda. 
    WUGN also ensured online participation through internet data support for virtual attendees. 
    Key learnings from the event were documented and disseminated within the community.
  </p>

  <h3 style="color: #1781cc;">Local Wikimania 2022 – Nigeria</h3>
  <p>
    In partnership with the <strong>Yoruba, Igbo, and Hausa Wikimedians User Groups</strong>, WUGN co-organized a local Wikimania gathering in <strong>Lagos</strong>. 
    The event mixed virtual and in-person components, featuring trainings, workshops, and brainstorming sessions. The theme of the 2022 global virtual Wikimania was <em>"The Festival Edition."</em>
  </p>

  <h3 style="color: #1781cc;">Wikimania 2022 – Singapore</h3>
  <p>
    For the first time, <strong>seven WUGN members</strong> attended Wikimania in Singapore. 
    Participants were encouraged to share their experiences with community members who couldn’t travel, ensuring wide knowledge transfer.
  </p>

  <h3 style="color: #1781cc;">Wiki Indaba 2023 – Morocco</h3>
  <p>
    WUGN participated in <strong>Wiki Indaba 2023</strong> held in Morocco. 
    Several members received scholarships, and the group sponsored one of its leaders from <strong>Abuja</strong> to attend. 
    These engagements underscore WUGN’s commitment to amplifying African voices in the global Wikimedia movement.
  </p>

